#!/usr/bin/env python3
"""Export the fixed QKeras model and test set for the portable C baseline."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from qkeras.utils import _add_supported_quantized_objects
from tensorflow.keras.models import load_model


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path(__file__).resolve().parent / "generated"
MODEL_PATH = ROOT / "model_3" / "KERAS_check_best_model.h5"
LAYER_NAMES = ("fc1", "fc2", "fc3", "output")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def c_float(value: np.float32) -> str:
    return float(np.float32(value)).hex() + "f"


def format_array(values, formatter, per_line=12):
    rendered = [formatter(value) for value in values]
    lines = []
    for start in range(0, len(rendered), per_line):
        lines.append("    " + ", ".join(rendered[start : start + per_line]))
    return ",\n".join(lines)


def export_sparse_layer(layer):
    kernel = layer.kernel_quantizer_internal(layer.kernel).numpy().astype(np.float32)
    bias = layer.bias_quantizer_internal(layer.bias).numpy().astype(np.float32)

    input_size, output_size = kernel.shape
    row_ptr = [0]
    column_indices = []
    values = []
    for output_index in range(output_size):
        for input_index in range(input_size):
            value = kernel[input_index, output_index]
            if value != 0.0:
                column_indices.append(input_index)
                values.append(value)
        row_ptr.append(len(values))

    return {
        "input_size": input_size,
        "output_size": output_size,
        "row_ptr": np.asarray(row_ptr, dtype=np.uint16),
        "column_indices": np.asarray(column_indices, dtype=np.uint8),
        "values": np.asarray(values, dtype=np.float32),
        "bias": bias,
        "dense_parameter_count": int(kernel.size),
        "nonzero_parameter_count": int(len(values)),
    }


def write_header(layers):
    parts = [
        "/* Generated by cpu_baseline/export_model.py; do not edit manually. */",
        "#ifndef HLS4ML_CPU_BASELINE_MODEL_DATA_H",
        "#define HLS4ML_CPU_BASELINE_MODEL_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "#define NN_INPUT_SIZE 16",
        "#define NN_OUTPUT_SIZE 5",
        "",
    ]

    for layer_name, data in layers.items():
        prefix = layer_name.upper()
        parts.extend(
            [
                f"#define {prefix}_INPUT_SIZE {data['input_size']}",
                f"#define {prefix}_OUTPUT_SIZE {data['output_size']}",
                f"#define {prefix}_NONZERO_COUNT {data['nonzero_parameter_count']}",
                f"static const uint16_t {layer_name}_row_ptr[{data['output_size'] + 1}] = {{",
                format_array(data["row_ptr"], lambda value: str(int(value))),
                "};",
                f"static const uint8_t {layer_name}_column_indices[{data['nonzero_parameter_count']}] = {{",
                format_array(data["column_indices"], lambda value: str(int(value))),
                "};",
                f"static const float {layer_name}_values[{data['nonzero_parameter_count']}] = {{",
                format_array(data["values"], c_float, per_line=6),
                "};",
                f"static const float {layer_name}_bias[{data['output_size']}] = {{",
                format_array(data["bias"], c_float, per_line=6),
                "};",
                "",
            ]
        )

    parts.extend(["#endif", ""])
    (OUTPUT / "model_data.h").write_text("\n".join(parts), encoding="utf-8")


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)

    custom_objects = {}
    _add_supported_quantized_objects(custom_objects)
    model = load_model(MODEL_PATH, custom_objects=custom_objects, compile=False)

    layers = {}
    for name in LAYER_NAMES:
        layers[name] = export_sparse_layer(model.get_layer(name))
    write_header(layers)

    x_test = np.ascontiguousarray(np.load(ROOT / "X_test.npy"), dtype=np.float32)
    y_test = np.load(ROOT / "y_test.npy")
    labels = np.ascontiguousarray(np.argmax(y_test, axis=1), dtype=np.uint8)
    reference_scores = np.ascontiguousarray(model.predict(x_test, batch_size=4096, verbose=0), dtype=np.float32)
    reference_labels = np.ascontiguousarray(np.argmax(reference_scores, axis=1), dtype=np.uint8)

    x_path = OUTPUT / "X_test_f32.bin"
    labels_path = OUTPUT / "y_test_labels_u8.bin"
    reference_scores_path = OUTPUT / "qkeras_reference_scores_f32.bin"
    reference_labels_path = OUTPUT / "qkeras_reference_labels_u8.bin"
    x_test.tofile(x_path)
    labels.tofile(labels_path)
    reference_scores.tofile(reference_scores_path)
    reference_labels.tofile(reference_labels_path)

    manifest = {
        "model": {
            "path": str(MODEL_PATH.relative_to(ROOT)),
            "sha256": sha256(MODEL_PATH),
            "architecture": [16, 64, 32, 32, 5],
            "parameter_count": int(model.count_params()),
            "weight_quantization": "QKeras quantized_bits(6, 0, alpha=1)",
            "activation_quantization": "QKeras quantized_relu(6), step=1/64, range=[0, 63/64]",
            "execution_arithmetic": "float32 with exported 6-bit parameter values and emulated 6-bit activations",
            "softmax": "stable float32 softmax included",
        },
        "test_set": {
            "samples": int(x_test.shape[0]),
            "input_shape": list(x_test.shape),
            "output_shape": list(y_test.shape),
        },
        "layers": {
            name: {
                "input_size": int(data["input_size"]),
                "output_size": int(data["output_size"]),
                "dense_weights": data["dense_parameter_count"],
                "nonzero_quantized_weights": data["nonzero_parameter_count"],
                "sparsity": 1.0 - data["nonzero_parameter_count"] / data["dense_parameter_count"],
            }
            for name, data in layers.items()
        },
        "artifacts": {},
    }

    for path in [x_path, labels_path, reference_scores_path, reference_labels_path, OUTPUT / "model_data.h"]:
        manifest["artifacts"][path.name] = {"bytes": path.stat().st_size, "sha256": sha256(path)}

    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
